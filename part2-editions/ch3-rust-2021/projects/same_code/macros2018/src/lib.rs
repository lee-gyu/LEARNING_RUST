//! 매크로 규칙의 `$p:pat`을 어떻게 해석할지는 매크로를 부른 크레이트가 아니라
//! 매크로를 정의한 크레이트(여기서는 2018 에디션)의 에디션이 정한다는 것을 보여 줍니다.

/// 어느 규칙이 입력을 받았는지 알려 줍니다. `shared/main.rs`의 `classify!`와 정의가 같습니다.
#[macro_export]
macro_rules! classify {
    ($p:pat) => {
        "규칙 1: 패턴 하나"
    };
    ($($t:tt)*) => {
        "규칙 2: 패턴이 아닌 토큰들"
    };
}
