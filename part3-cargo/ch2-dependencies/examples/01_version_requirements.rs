//! 버전 요구 사항이 어떤 버전을 받아들이는지 봅니다.
//!
//! `Cargo.toml`의 `heck = "0.5"`에서 `"0.5"`는 버전 하나가 아니라 범위입니다.
//! 요구 사항의 종류마다 그 범위가 어떻게 달라지는지 같은 버전 목록에 대 봅니다.
//!
//! 판정에는 `semver` 크레이트를 씁니다. crates.io의 설명이
//! "Parser and evaluator for Cargo's flavor of Semantic Versioning"인,
//! Cargo 방식의 버전과 요구 사항을 해석하는 크레이트입니다.
//!
//! 실행: cargo run -p p3-ch2-dependencies --example 01_version_requirements

use semver::{Version, VersionReq};

/// 레지스트리에 게시돼 있다고 칠 버전들입니다. 낮은 것부터 적었습니다.
const PUBLISHED: [&str; 10] = [
    "0.0.3",
    "0.2.3",
    "0.2.9",
    "0.3.0",
    "1.2.3",
    "1.2.9",
    "1.3.0",
    "1.9.0",
    "2.0.0",
    "2.1.0-beta.1",
];

/// 요구 사항이 받아들이는 버전을 `PUBLISHED`에서 골라 한 줄로 만듭니다.
fn accepted(requirement: &str) -> String {
    // `Cargo.toml`에 적는 문자열을 그대로 해석합니다. 연산자가 없으면 캐럿(`^`)으로 봅니다.
    let req = VersionReq::parse(requirement).expect("올바른 요구 사항이어야 합니다");
    let matched: Vec<&str> = PUBLISHED
        .iter()
        .copied()
        .filter(|v| req.matches(&Version::parse(v).expect("올바른 버전이어야 합니다")))
        .collect();
    if matched.is_empty() {
        "(없음)".to_string()
    } else {
        matched.join(" ")
    }
}

fn show(title: &str, requirements: &[&str]) {
    println!("== {title} ==");
    for requirement in requirements {
        // 따옴표까지 넣어 Cargo.toml에 적는 모양 그대로 보여 줍니다.
        let quoted = format!("\"{requirement}\"");
        println!("{quoted:<16} {}", accepted(requirement));
    }
    println!();
}

/// 두 버전이 Cargo의 기준으로 호환되는지 봅니다.
///
/// 기준: 0이 아닌 가장 왼쪽 자리가 같으면 호환됩니다. 낮은 쪽에 캐럿을 붙인 요구 사항이
/// 높은 쪽을 받아들이는지로 같은 판정을 얻을 수 있습니다.
fn compatible(low: &str, high: &str) -> bool {
    let caret = VersionReq::parse(&format!("^{low}")).expect("올바른 요구 사항이어야 합니다");
    caret.matches(&Version::parse(high).expect("올바른 버전이어야 합니다"))
}

fn main() {
    println!("게시된 버전: {}", PUBLISHED.join(" "));
    println!();

    // 연산자를 적지 않으면 캐럿 요구 사항입니다. "적은 버전 이상, 호환되는 범위 안"을 뜻합니다.
    show(
        "기본(캐럿): 호환되는 범위",
        &["1.2.3", "^1.2.3", "1.2", "1"],
    );
    // 출력: "1.2.3"          1.2.3 1.2.9 1.3.0 1.9.0
    // 출력: "^1.2.3"         1.2.3 1.2.9 1.3.0 1.9.0
    // 출력: "1.2"            1.2.3 1.2.9 1.3.0 1.9.0
    // 출력: "1"              1.2.3 1.2.9 1.3.0 1.9.0

    // 0.x에서는 둘째 자리가, 0.0.x에서는 셋째 자리가 "호환되지 않는 변경"의 자리입니다.
    show(
        "0으로 시작하는 버전의 캐럿",
        &["0.2.3", "0.2", "0.0.3", "0"],
    );
    // 출력: "0.2.3"          0.2.3 0.2.9
    // 출력: "0.2"            0.2.3 0.2.9
    // 출력: "0.0.3"          0.0.3
    // 출력: "0"              0.0.3 0.2.3 0.2.9 0.3.0

    // 틸드는 캐럿보다 좁습니다. 둘째 자리 이상 적으면 첫째·둘째 자리는 그대로 두고 셋째 자리만,
    // 첫째 자리만 적으면 둘째·셋째 자리가 올라가도록 허용합니다.
    show("틸드: 더 좁은 범위", &["~1.2.3", "~1.2", "~1"]);
    // 출력: "~1.2.3"         1.2.3 1.2.9
    // 출력: "~1.2"           1.2.3 1.2.9
    // 출력: "~1"             1.2.3 1.2.9 1.3.0 1.9.0

    show("와일드카드: 별표 자리는 무엇이든", &["1.*", "1.2.*", "*"]);
    // 출력: "1.*"            1.2.3 1.2.9 1.3.0 1.9.0
    // 출력: "1.2.*"          1.2.3 1.2.9
    // 출력: "*"              0.0.3 0.2.3 0.2.9 0.3.0 1.2.3 1.2.9 1.3.0 1.9.0 2.0.0

    // 비교 연산자는 범위의 끝을 직접 정합니다. 쉼표로 이으면 모두 만족해야 합니다.
    show(
        "비교와 여러 조건",
        &[">=1.2.9", "<1.3", "=1.2.3", ">=1.2.9, <1.9", "<1.2, ^1.2.2"],
    );
    // 출력: ">=1.2.9"        1.2.9 1.3.0 1.9.0 2.0.0
    // 출력: "<1.3"           0.0.3 0.2.3 0.2.9 0.3.0 1.2.3 1.2.9
    // 출력: "=1.2.3"         1.2.3
    // 출력: ">=1.2.9, <1.9"  1.2.9 1.3.0
    // 출력: "<1.2, ^1.2.2"   (없음)

    // 프리릴리스는 요구 사항에 프리릴리스를 직접 적었을 때만 후보가 됩니다.
    show("프리릴리스", &["2", "2.1.0-beta.1", ">=2.0.0"]);
    // 출력: "2"              2.0.0
    // 출력: "2.1.0-beta.1"   2.1.0-beta.1
    // 출력: ">=2.0.0"        2.0.0

    println!("== 두 버전은 호환되는가 ==");
    for (low, high) in [
        ("1.2.3", "1.9.0"),
        ("1.9.0", "2.0.0"),
        ("0.2.3", "0.2.9"),
        ("0.2.9", "0.3.0"),
        ("0.0.3", "0.0.4"),
    ] {
        let verdict = if compatible(low, high) {
            "호환됨 (Cargo가 하나로 합칩니다)"
        } else {
            "호환되지 않음 (함께 필요하면 둘 다 빌드합니다)"
        };
        println!("{low}, {high}: {verdict}");
    }
    // 출력: 1.2.3, 1.9.0: 호환됨 (Cargo가 하나로 합칩니다)
    // 출력: 1.9.0, 2.0.0: 호환되지 않음 (함께 필요하면 둘 다 빌드합니다)
    // 출력: 0.2.3, 0.2.9: 호환됨 (Cargo가 하나로 합칩니다)
    // 출력: 0.2.9, 0.3.0: 호환되지 않음 (함께 필요하면 둘 다 빌드합니다)
    // 출력: 0.0.3, 0.0.4: 호환되지 않음 (함께 필요하면 둘 다 빌드합니다)
}
