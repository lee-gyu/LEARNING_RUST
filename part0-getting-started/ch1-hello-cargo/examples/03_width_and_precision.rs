// 예제 03: 출력 모양 다듬기 — 너비, 정렬, 채움 문자, 정밀도, 부호
//
// 보여 주는 것: 자리표시자 안의 `:` 뒤에 서식 지정(format spec)을 붙여
//               값이 차지할 칸 수와 정렬 방향, 소수점 자릿수를 정하는 방법.
//               `[`와 `]`는 공백이 몇 칸인지 눈으로 보이게 하려고 붙였습니다.
//
// 실행: cargo run -p p0-ch1-hello-cargo --example 03_width_and_precision

fn main() {
    // 서식 지정의 순서: {인자:[채움][정렬][부호][0][너비][.정밀도]}
    // 모두 생략할 수 있고, 쓰는 것만 이 순서대로 적습니다.

    // 너비: `:` 뒤의 숫자는 "최소 몇 칸을 차지할지"입니다.
    // 정렬을 적지 않으면 숫자는 오른쪽, 문자열은 왼쪽에 붙습니다.
    let n = 42;
    let s = "ab";
    println!("[{n:6}] [{s:6}]"); // 출력: [    42] [ab    ]

    // 값이 너비보다 길면 잘리지 않고 그대로 다 출력됩니다. 너비는 "최소" 칸 수입니다.
    println!("[{n:1}]"); // 출력: [42]

    // 정렬: `<` 왼쪽, `^` 가운데, `>` 오른쪽
    println!("[{s:<6}] [{s:^6}] [{s:>6}]"); // 출력: [ab    ] [  ab  ] [    ab]

    // 채움 문자: 정렬 기호 바로 앞에 적은 문자로 빈칸을 채웁니다.
    println!("[{s:*^10}] [{s:->6}]"); // 출력: [****ab****] [----ab]

    // 숫자 앞을 0으로 채우기: 너비 앞에 `0`을 붙입니다.
    // 음수 부호는 0보다 앞에 오므로 `-0042`처럼 출력됩니다.
    let negative = -42;
    println!("[{n:05}] [{negative:05}]"); // 출력: [00042] [-0042]

    // 부호: `+`를 붙이면 양수에도 `+`가 표시됩니다.
    println!("[{n:+}] [{negative:+}]"); // 출력: [+42] [-42]

    // 정밀도: `.숫자`는 실수의 소수점 아래 자릿수입니다.
    // 자릿수보다 길면 반올림하고, 짧으면 0을 덧붙여 자릿수를 맞춥니다.
    let temp = 36.567;
    println!("{temp} → {temp:.1} → {temp:.2} → {temp:.5}");
    // 출력: 36.567 → 36.6 → 36.57 → 36.56700

    // 너비와 정밀도를 함께: 전체 8칸, 소수점 아래 1자리
    println!("[{temp:8.1}] [{temp:<8.1}]"); // 출력: [    36.6] [36.6    ]

    // 너비를 변수로 정하기: `너비이름$`처럼 `$`를 붙이면 그 변수 값이 너비가 됩니다.
    let width = 7;
    println!("[{s:>width$}]"); // 출력: [     ab]

    // 위 기능을 조합하면 열이 맞는 표를 만들 수 있습니다.
    let apple = 1200;
    let banana = 350;
    let total = apple + banana;
    println!("{:<8}|{:>7}", "item", "price");
    println!("{:-<8}+{:->7}", "", "");
    println!("{:<8}|{apple:>7}", "apple");
    println!("{:<8}|{banana:>7}", "banana");
    println!("{:<8}|{total:>7}", "total");
    // 출력: item    |  price
    // 출력: --------+-------
    // 출력: apple   |   1200
    // 출력: banana  |    350
    // 출력: total   |   1550

    // 주의: 너비는 화면의 칸 수가 아니라 글자 수(정확히는 유니코드 문자 개수)로 셉니다.
    // 한글 한 글자는 터미널에서 보통 영문 두 글자만큼의 폭을 차지하지만 너비 계산에서는
    // 한 글자로 세기 때문에, 한글이 섞이면 같은 너비를 줘도 열이 어긋나 보입니다.
    println!("[{:<6}]", "apple");
    println!("[{:<6}]", "사과");
    // 출력: [apple ]
    // 출력: [사과    ]   ← "사과" 2글자 + 공백 4칸. 터미널에서는 위 줄보다 길게 보입니다.
}
