// 예제 04: 같은 값을 다른 형식으로 — 진법, 지수 표기, 디버그 형식 `{:?}`
//
// 보여 주는 것: 서식 지정의 맨 끝에 붙이는 형식 문자(`b`, `o`, `x`, `X`, `e`, `?`)가
//               값을 "어떤 표기법으로" 보여 줄지 정한다는 것.
//
// 실행: cargo run -p p0-ch1-hello-cargo --example 04_number_formats

fn main() {
    // 형식 문자를 적지 않은 `{}`는 사람이 읽기 좋은 기본 형식(Display)입니다.
    // 정수라면 10진수로 출력됩니다.
    let n = 255;
    println!("10진수: {n}"); // 출력: 10진수: 255

    // 형식 문자를 붙이면 같은 정수를 다른 진법으로 보여 줍니다. 값 자체는 그대로입니다.
    println!("2진수: {n:b}"); // 출력: 2진수: 11111111
    println!("8진수: {n:o}"); // 출력: 8진수: 377
    println!("16진수: {n:x} / {n:X}"); // 출력: 16진수: ff / FF

    // `#`(대체 형식)를 붙이면 어느 진법인지 알 수 있도록 접두사가 붙습니다.
    println!("{n:#b} {n:#o} {n:#x}"); // 출력: 0b11111111 0o377 0xff

    // 형식 문자도 너비·채움과 함께 쓸 수 있습니다. 순서는 항상 너비 다음, 맨 끝입니다.
    // 비트를 다룰 때는 자릿수를 고정해 0으로 채우는 경우가 많습니다.
    let flags = 5;
    println!("{flags:08b}"); // 출력: 00000101
    // `#`와 `0`을 함께 쓰면 접두사 `0b`도 너비 10칸에 포함됩니다.
    println!("{flags:#010b}"); // 출력: 0b00000101

    // 실수는 `e`/`E`로 지수 표기(과학적 표기법)를 쓸 수 있습니다.
    // 1.2345e3은 1.2345 × 10³ 이라는 뜻입니다.
    let big = 1234.5;
    let small = 0.00012;
    println!("{big:e} {small:E}"); // 출력: 1.2345e3 1.2E-4

    // `?`는 디버그 형식(Debug)입니다. 사람에게 보여 주기보다는 개발자가 값의 정확한
    // 모양을 확인하려고 씁니다. 같은 값이라도 `{}`와 `{:?}`의 결과가 다를 수 있습니다.
    let whole = 3.0;
    println!("{whole} vs {whole:?}"); // 출력: 3 vs 3.0
    // 실수 3.0을 `{}`로 찍으면 3이 되지만, `{:?}`는 실수라는 것이 드러나게 3.0으로 찍습니다.

    // 문자열을 `{:?}`로 찍으면 따옴표가 붙고, 따옴표 같은 특수 문자는 `\"`처럼 보입니다.
    // 문자열의 시작과 끝, 공백이 어디까지인지 확인할 때 유용합니다.
    let quote = "그가 \"안녕\"이라고 했다 ";
    println!("[{quote}]"); // 출력: [그가 "안녕"이라고 했다 ]
    println!("[{quote:?}]"); // 출력: ["그가 \"안녕\"이라고 했다 "]

    // 여러 값을 묶은 배열(ch3에서 다룹니다)처럼 `{}`로는 출력할 수 없는 값도
    // `{:?}`로는 출력할 수 있습니다. `{}`를 쓰면 컴파일 에러가 납니다.
    let scores = [90, 85, 77];
    println!("{scores:?}"); // 출력: [90, 85, 77]
}
