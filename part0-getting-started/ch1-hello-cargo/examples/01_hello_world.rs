// 예제 01: 가장 작은 Rust 프로그램
//
// 보여 주는 것: 실행 파일은 `main` 함수에서 시작하고, `println!` 매크로가
//               문자열 한 줄을 화면(표준 출력)에 찍는다는 것.
//
// 실행 (저장소 어디에서나):
//   cargo run -p p0-ch1-hello-cargo --example 01_hello_world
//
// Cargo 없이 rustc로 직접 컴파일 (챕터 디렉터리에서):
//   rustc --edition 2024 examples/01_hello_world.rs --out-dir /tmp/rust-ch1
//   /tmp/rust-ch1/01_hello_world

// `fn`은 함수를 정의하는 키워드입니다. 실행 파일로 만들어지는 Rust 프로그램은
// 언제나 `main`이라는 이름의 함수에서 시작합니다. 운영체제가 프로그램을 실행하면
// 가장 먼저 이 함수가 호출되기 때문에, `main`이 없으면 실행 파일을 만들 수 없습니다.
// 괄호 `()`가 비어 있으니 매개변수(parameter)가 없고, `->`로 반환 타입을 적지 않았으니
// 돌려주는 값도 없습니다. 함수 본문은 반드시 중괄호 `{ }`로 감쌉니다.
fn main() {
    // `println` 뒤의 `!`는 이것이 함수가 아니라 매크로(macro)라는 표시입니다.
    // Rust의 함수는 인자 개수가 정해져 있어야 하지만, 출력할 값의 개수는 그때그때
    // 다릅니다. 매크로는 컴파일할 때 그 자리에 알맞은 코드를 만들어 넣기 때문에
    // 인자 개수가 달라도 되고, 서식 문자열이 올바른지도 컴파일 시점에 검사할 수 있습니다.
    println!("Hello, world!"); // 출력: Hello, world!

    // 줄 끝의 세미콜론(`;`)은 "이 작업은 여기서 끝"이라는 표시입니다.
    // Rust 코드는 대부분의 줄이 세미콜론으로 끝납니다.
    // Rust의 문자열은 UTF-8이므로 한글도 그대로 출력됩니다(문자열은 ch8에서 자세히 다룹니다).
    println!("안녕하세요, Rust!"); // 출력: 안녕하세요, Rust!
}
