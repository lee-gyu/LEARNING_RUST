// 예제 02: 서식 문자열의 자리표시자 `{}`와 인자
//
// 보여 주는 것: `println!`의 첫 번째 인자(서식 문자열) 안의 `{}`가 뒤에 오는 값으로
//               바뀌는 규칙. 순서대로, 번호로, 이름으로, 변수를 직접 넣는 네 가지 방법.
//
// 실행: cargo run -p p0-ch1-hello-cargo --example 02_placeholders

fn main() {
    // `let`은 값에 이름을 붙이는 키워드입니다. 자세한 내용은 ch2와 ch3에서 다룹니다.
    // 여기서는 "이름표가 붙은 값"이라고만 생각하면 충분합니다.
    let year = 2015;
    let month = 5;
    let day = 15;

    // 1) 순서대로: `{}` 하나에 인자 하나가 앞에서부터 차례로 들어갑니다.
    //    인자는 문자열이 아니어도 됩니다. 숫자도 `{}`로 출력됩니다.
    println!("Rust 1.0 출시일: {}년 {}월 {}일", year, month, day);
    // 출력: Rust 1.0 출시일: 2015년 5월 15일

    // 인자 자리에는 계산식을 써도 됩니다. 식을 먼저 계산한 결과가 들어갑니다.
    println!("{} + {} = {}", month, day, month + day);
    // 출력: 5 + 15 = 20

    // 2) 번호로: `{0}`, `{1}`처럼 인자의 위치(0부터 셈)를 적으면
    //    같은 인자를 여러 번 쓰거나 순서를 바꿀 수 있습니다.
    let a = "철수";
    let b = "영희";
    println!("{0}가 {1}에게 인사하고, {1}가 {0}에게 답합니다.", a, b);
    // 출력: 철수가 영희에게 인사하고, 영희가 철수에게 답합니다.

    // 3) 이름으로: `이름 = 값` 형태로 인자를 넘기고 `{이름}`으로 꺼내 씁니다.
    //    인자가 많을 때 어느 값이 어디에 들어가는지 읽기 쉬워집니다.
    //    이름 인자는 위치 인자보다 뒤에 와야 합니다.
    println!(
        "가로 {w}, 세로 {h}인 사각형의 넓이는 {area}입니다.",
        w = 3,
        h = 4,
        area = 3 * 4
    );
    // 출력: 가로 3, 세로 4인 사각형의 넓이는 12입니다.

    // 4) 변수 직접 넣기: 같은 이름의 변수가 있으면 `{변수이름}`만 써도 됩니다.
    //    인자 목록을 따로 적지 않아도 되므로 요즘 Rust 코드에서 가장 흔한 형태입니다.
    println!("{year}년 {month}월 {day}일");
    // 출력: 2015년 5월 15일

    // 단, `{}` 안에는 변수 이름만 쓸 수 있고 `{month + day}` 같은 식은 쓸 수 없습니다.
    // 식은 1)처럼 인자로 넘겨야 합니다.
    println!("{year}년의 다음 해는 {}년입니다.", year + 1);
    // 출력: 2015년의 다음 해는 2016년입니다.

    // 중괄호 문자 자체를 찍으려면 `{{`, `}}`처럼 두 번 씁니다.
    // `{` 하나는 자리표시자의 시작으로 해석되기 때문입니다.
    println!("자리표시자는 {{}} 모양이고, 값을 감싸면 {{{day}}}가 됩니다.");
    // 출력: 자리표시자는 {} 모양이고, 값을 감싸면 {15}가 됩니다.

    // 인자 없이 `println!()`만 쓰면 빈 줄 하나가 출력됩니다.
    println!();
    println!("바로 위에 빈 줄이 있습니다.");
    // 출력: (빈 줄)
    // 출력: 바로 위에 빈 줄이 있습니다.
}
