// Box<T>로 값을 힙에 두는 방법과, 스마트 포인터가 무엇인지 확인합니다.
// - Box는 힙에 놓인 값을 소유하는 포인터입니다. Box 자체는 포인터 한 칸 크기입니다.
// - 큰 데이터를 Box에 담아 두면 이동할 때 포인터만 복사됩니다.
// - 이미 써 온 String과 Vec<T>도 힙 데이터를 소유하는 스마트 포인터입니다.
//
// 실행: cargo run -p p0-ch14-smart-pointers --example 01_box_basics

// 배열을 Box째로 받아 소유권을 넘겨받는 함수입니다.
// 인자로 넘어오는 것은 포인터 한 칸뿐이고, 1만 바이트짜리 배열은 힙에서 움직이지 않습니다.
fn first_and_len(data: Box<[u8; 10_000]>) -> (u8, usize) {
    (data[0], data.len())
} // 새 소유자 data가 여기서 버려지므로 힙에 있던 배열도 함께 해제됩니다.

fn main() {
    println!("1. Box::new는 값을 힙에 두고, 그 값을 소유하는 Box를 돌려줍니다");
    let b = Box::new(5);
    // 출력할 때는 Box가 아니라 안에 든 값이 출력됩니다.
    println!("    b = {b}"); // 출력: b = 5
    // 계산에 쓰려면 `*`로 포인터를 따라가 안의 값을 꺼냅니다(03번 예제에서 자세히 봅니다).
    println!("    *b + 1 = {}", *b + 1); // 출력: *b + 1 = 6

    println!("2. Box 자체의 크기는 가리키는 데이터와 상관없이 포인터 한 칸입니다");
    // 아래 크기는 64비트 환경 기준입니다. 포인터 한 칸이 8바이트입니다.
    println!("    i32:              {}바이트", size_of::<i32>()); // 출력: i32:              4바이트
    println!("    Box<i32>:         {}바이트", size_of::<Box<i32>>()); // 출력: Box<i32>:         8바이트
    println!("    [u8; 10000]:      {}바이트", size_of::<[u8; 10_000]>()); // 출력: [u8; 10000]:      10000바이트
    println!(
        "    Box<[u8; 10000]>: {}바이트",
        size_of::<Box<[u8; 10_000]>>()
    ); // 출력: Box<[u8; 10000]>: 8바이트
    println!("    &i32:             {}바이트", size_of::<&i32>()); // 출력: &i32:             8바이트
    // 참조와 Box는 크기가 같습니다. 차이는 크기가 아니라 "소유하는가"에 있습니다.

    println!("3. Box를 이동하면 포인터만 복사되고, 힙의 데이터는 그 자리에 있습니다");
    let big = Box::new([7u8; 10_000]);
    // as_ptr()은 배열이 놓인 힙 주소입니다. 주소 값은 실행할 때마다 달라지므로 비교 결과만 출력합니다.
    let heap_before = big.as_ptr();
    let moved = big; // 소유권 이동. 복사되는 것은 Box(8바이트)뿐입니다.
    println!(
        "    이동 후에도 같은 힙 주소를 가리키는가? {}",
        moved.as_ptr() == heap_before
    ); // 출력: 이동 후에도 같은 힙 주소를 가리키는가? true
    let (first, len) = first_and_len(moved); // 함수 인자로 넘길 때도 마찬가지입니다.
    println!("    first = {first}, len = {len}"); // 출력: first = 7, len = 10000

    println!("4. String과 Vec<T>도 힙 데이터를 소유하는 스마트 포인터입니다");
    let s = String::from("안녕");
    let mut v = vec![1, 2];
    v.push(3); // 원소가 늘어나는 곳은 힙입니다. v 자체의 크기는 그대로입니다.
    // 둘 다 (포인터, 길이, 용량) 세 칸짜리 구조체입니다(ch4, ch8).
    // 글자와 원소는 힙에 있고, 스택에는 그곳을 가리키는 포인터와 정보만 있습니다.
    println!(
        "    String: {}바이트, Vec<i32>: {}바이트",
        size_of::<String>(),
        size_of::<Vec<i32>>()
    ); // 출력: String: 24바이트, Vec<i32>: 24바이트
    println!(
        "    s의 글자 {}바이트, v의 원소 {}개는 힙에 있습니다",
        s.len(),
        v.len()
    ); // 출력: s의 글자 6바이트, v의 원소 3개는 힙에 있습니다
    // 둘 다 Deref(03번 예제)와 Drop(04번 예제)을 구현합니다. 그래서 스마트 포인터입니다.

    println!("5. main이 끝나면 b, s, v가 버려지면서 각자 소유한 힙 메모리를 해제합니다");
} // 이 정리는 아무것도 출력하지 않습니다. drop 시점을 눈으로 보는 방법은 04번 예제에서 다룹니다.
