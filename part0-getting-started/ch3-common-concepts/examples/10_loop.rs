// 이 예제가 보여 주는 것: `loop` — 무한 반복, `continue`, `break`로 값 반환하기, 루프 레이블
// 실행: cargo run -p p0-ch3-common-concepts --example 10_loop

fn main() {
    // ── 1. `loop`와 `break` ─────────────────────────────────────────────
    // `loop`는 `break`를 만날 때까지 본문을 끝없이 반복합니다.
    // `continue`는 이번 반복의 나머지를 건너뛰고 다음 반복으로 넘어갑니다.
    let mut n = 0;
    loop {
        n += 1;
        if n > 7 {
            break;
        }
        if n % 2 == 0 {
            continue; // 짝수는 출력하지 않고 건너뜁니다.
        }
        println!("홀수: {n}");
    }
    // 출력:
    // 홀수: 1
    // 홀수: 3
    // 홀수: 5
    // 홀수: 7

    // ── 2. `break 값`: `loop`도 값을 내는 표현식입니다 ──────────────────────
    // "조건을 만족할 때까지 반복해서 찾은 값"을 변수에 바로 담을 수 있습니다.
    // 아래는 2를 계속 곱해서 처음으로 1000 이상이 되는 수를 찾습니다.
    let mut power = 1;
    let first_over_1000 = loop {
        power *= 2;
        if power >= 1000 {
            break power; // 루프를 끝내면서 `power`의 값을 `loop` 표현식의 값으로 내보냅니다.
        }
    };
    println!("처음으로 1000 이상이 되는 2의 거듭제곱: {first_over_1000}"); // 출력: 처음으로 1000 이상이 되는 2의 거듭제곱: 1024

    // `break`에 값을 실을 수 있는 것은 `loop`뿐입니다. `while`과 `for`는 조건이 거짓이 되거나
    // 반복할 원소가 떨어져서 `break` 없이도 끝날 수 있으므로, 그때 낼 값이 정해지지 않기 때문입니다.
    // `while` 안에서 `break 값`을 쓰면 E0571 에러가 납니다.

    // ── 3. 루프 레이블: 바깥 루프를 지정해서 빠져나가기 ─────────────────────
    // 그냥 `break`는 가장 안쪽 루프만 끝냅니다. 레이블은 작은따옴표로 시작하는 이름(`'outer`)이며,
    // `break 'outer`라고 쓰면 그 레이블이 붙은 바깥 루프까지 한 번에 끝냅니다.
    // 아래는 구구단 2단부터 차례로 훑다가 곱이 처음으로 50을 넘는 지점을 찾습니다.
    // `loop`가 내는 값이 튜플이므로 `let (a, b) = ...` 패턴으로 바로 구조 분해해서 받습니다.
    let mut dan = 2;
    let (found_dan, found_n) = 'outer: loop {
        let mut n = 1;
        loop {
            if n > 9 {
                break; // 안쪽 루프만 끝냅니다. 다음 단으로 넘어갑니다.
            }
            if dan * n > 50 {
                // 바깥 루프까지 끝내면서 (단, 곱하는 수) 튜플을 값으로 내보냅니다.
                break 'outer (dan, n);
            }
            n += 1;
        }
        println!("{dan}단에는 50을 넘는 곱이 없습니다");
        dan += 1;
    };
    // `break 'outer`로 빠져나간 6단에서는 "6단에는 ..." 줄이 출력되지 않습니다.
    let product = found_dan * found_n;
    println!("처음으로 50을 넘는 곱: {found_dan} x {found_n} = {product}");
    // 출력:
    // 2단에는 50을 넘는 곱이 없습니다
    // 3단에는 50을 넘는 곱이 없습니다
    // 4단에는 50을 넘는 곱이 없습니다
    // 5단에는 50을 넘는 곱이 없습니다
    // 처음으로 50을 넘는 곱: 6 x 9 = 54

    // `continue 'outer`처럼 쓰면 바깥 루프의 다음 반복으로 바로 넘어갑니다.
    // 3~5단에서 첫 번째 짝수 곱만 출력하고 곧바로 다음 단으로 넘어가 봅니다.
    // 카운터를 반복의 맨 앞에서 늘려 두면, `continue`가 증가 코드를 건너뛰는 실수를 피할 수 있습니다.
    let mut dan = 2;
    'dans: loop {
        dan += 1;
        if dan > 5 {
            break;
        }
        let mut n = 0;
        loop {
            n += 1;
            if dan * n % 2 == 0 {
                println!("{dan}단의 첫 짝수 곱: {dan} x {n} = {}", dan * n);
                continue 'dans; // 안쪽 루프의 나머지와 바깥 루프의 나머지를 모두 건너뜁니다.
            }
        }
    }
    // 출력:
    // 3단의 첫 짝수 곱: 3 x 2 = 6
    // 4단의 첫 짝수 곱: 4 x 1 = 4
    // 5단의 첫 짝수 곱: 5 x 2 = 10
}
