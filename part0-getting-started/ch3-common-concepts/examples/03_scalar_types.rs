// 이 예제가 보여 주는 것: 스칼라 타입(scalar type) 네 가지 — 정수, 부동소수점 수, 불리언, 문자
// 실행: cargo run -p p0-ch3-common-concepts --example 03_scalar_types

fn main() {
    // ── 1. 정수 ──────────────────────────────────────────────
    // 타입을 적지 않으면 정수는 `i32`가 됩니다.
    // `i`는 부호 있는(signed) 정수, `u`는 부호 없는(unsigned) 정수이고 숫자는 비트 수입니다.
    let default_int = 42; // i32
    let small: u8 = 255; // u8의 범위는 0~255
    let negative: i8 = -128; // i8의 범위는 -128~127
    println!("{default_int} {small} {negative}"); // 출력: 42 255 -128

    // 각 정수 타입의 최솟값·최댓값은 `MIN`, `MAX`로 확인할 수 있습니다.
    println!("i8: {} ~ {}", i8::MIN, i8::MAX); // 출력: i8: -128 ~ 127
    println!("u32 최댓값: {}", u32::MAX); // 출력: u32 최댓값: 4294967295
    // `usize`/`isize`의 크기는 컴퓨터 아키텍처에 따라 다릅니다(64비트 환경에서 64).
    println!("usize 비트 수: {}", usize::BITS); // 출력: usize 비트 수: 64  (64비트 환경 기준)

    // 정수 리터럴은 여러 진법으로 쓸 수 있고, `_`로 자릿수를 끊을 수 있습니다.
    let decimal = 98_222;
    let hex = 0xff;
    let octal = 0o77;
    let binary = 0b1111_0000;
    let byte = b'A'; // 바이트 리터럴은 u8 전용입니다. 'A'의 ASCII 코드 값이 들어갑니다.
    let suffixed = 57u8; // 숫자 뒤에 타입을 붙여 타입을 정할 수도 있습니다.
    println!("{decimal} {hex} {octal} {binary} {byte} {suffixed}"); // 출력: 98222 255 63 240 65 57

    // ── 2. 부동소수점 수 ─────────────────────────────────────
    // 타입을 적지 않으면 `f64`가 됩니다. 현대 CPU에서 `f32`와 속도가 거의 같고 더 정밀하기 때문입니다.
    let x = 2.0; // f64
    let y: f32 = 3.0; // f32
    // `{}`는 소수점 아래가 0이면 생략해 보여 줍니다. 값이 정수로 바뀐 것은 아닙니다.
    // `{:?}`(디버그 형식)로 출력하면 실수라는 것이 드러나도록 `2.0`처럼 보여 줍니다.
    println!("{x} {y}"); // 출력: 2 3
    println!("{x:?} {y:?}"); // 출력: 2.0 3.0
    // IEEE-754 표준을 따르므로 다른 언어와 마찬가지로 십진수를 정확히 나타내지 못하는 경우가 있습니다.
    println!("0.1 + 0.2 = {}", 0.1 + 0.2); // 출력: 0.1 + 0.2 = 0.30000000000000004

    // ── 3. 수치 연산 ─────────────────────────────────────────
    println!("5 + 10 = {}", 5 + 10); // 출력: 5 + 10 = 15
    println!("95.5 - 4.3 = {}", 95.5 - 4.3); // 출력: 95.5 - 4.3 = 91.2
    println!("4 * 30 = {}", 4 * 30); // 출력: 4 * 30 = 120
    // 정수끼리 나누면 결과도 정수이고, 소수점 아래는 0 쪽으로 버려집니다.
    println!("7 / 2 = {}", 7 / 2); // 출력: 7 / 2 = 3
    println!("-5 / 3 = {}", -5 / 3); // 출력: -5 / 3 = -1
    println!("7.0 / 2.0 = {}", 7.0 / 2.0); // 출력: 7.0 / 2.0 = 3.5
    println!("43 % 5 = {}", 43 % 5); // 출력: 43 % 5 = 3

    // Rust는 정수와 실수를 자동으로 섞어 계산하지 않습니다. `1 + 2.5`는 컴파일 에러(E0277)입니다.
    // 타입을 바꾸려면 `as`로 직접 변환합니다. 숨은 변환이 없으므로 정밀도 손실이 코드에 드러납니다.
    let total_score = 17; // i32
    let count = 4; // i32
    let average = total_score as f64 / count as f64;
    println!("평균 = {average}"); // 출력: 평균 = 4.25
    println!("정수 나눗셈 = {}", total_score / count); // 출력: 정수 나눗셈 = 4

    // ── 4. 불리언 ────────────────────────────────────────────
    // `bool`의 값은 `true`와 `false` 두 가지입니다. 비교 연산의 결과가 `bool`입니다.
    let t = true;
    let f: bool = false;
    let is_big = 10 > 5;
    println!("{t} {f} {is_big}"); // 출력: true false true

    // ── 5. 문자 ──────────────────────────────────────────────
    // `char`는 작은따옴표로 쓰고, 유니코드 스칼라 값 하나를 4바이트로 담습니다.
    // 그래서 영문자뿐 아니라 한글, 수학 기호, 이모지도 `char` 하나에 들어갑니다.
    // (큰따옴표 "..."는 문자열이며 `char`가 아닙니다.)
    let c = 'z';
    let hangul = '한';
    let z: char = 'ℤ';
    let heart_eyed_cat = '😻';
    println!("{c} {hangul} {z} {heart_eyed_cat}"); // 출력: z 한 ℤ 😻
    // `as u32`로 바꾸면 그 문자의 유니코드 코드 포인트 값을 볼 수 있습니다.
    // `{:X}`는 정수를 16진수 대문자로 출력하는 서식입니다.
    println!("'한'의 코드 포인트: U+{:X}", hangul as u32); // 출력: '한'의 코드 포인트: U+D55C
}
