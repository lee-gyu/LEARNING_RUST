// 이 예제가 보여 주는 것: 복합 타입(compound type) 두 가지 — 튜플(tuple)과 배열(array)
// 실행: cargo run -p p0-ch3-common-concepts --example 05_compound_types

fn main() {
    // ── 1. 튜플: 서로 다른 타입의 값 여러 개를 하나로 묶습니다 ──────────────
    // 길이가 고정이어서 한번 만들면 원소를 늘리거나 줄일 수 없습니다.
    let tup: (i32, f64, char) = (500, 6.4, '가');

    // `{:?}`(디버그 형식)로 튜플 전체를 출력할 수 있습니다. `{}`로는 출력할 수 없습니다.
    println!("tup = {tup:?}"); // 출력: tup = (500, 6.4, '가')

    // 구조 분해(destructuring): 패턴으로 튜플을 풀어 각 원소를 변수에 담습니다.
    let (x, y, z) = tup;
    println!("x = {x}, y = {y}, z = {z}"); // 출력: x = 500, y = 6.4, z = 가

    // 점(.)과 0부터 시작하는 번호로 원소 하나에 접근할 수도 있습니다.
    println!("tup.0 = {}, tup.2 = {}", tup.0, tup.2); // 출력: tup.0 = 500, tup.2 = 가

    // `mut` 튜플은 원소를 바꿀 수 있습니다. 단, 타입과 길이는 그대로입니다.
    let mut point = (0, 0);
    point.0 = 3;
    point.1 += 4;
    println!("point = {point:?}"); // 출력: point = (3, 4)

    // 원소가 없는 튜플 `()`를 유닛(unit)이라고 부릅니다. "의미 있는 값이 없음"을 나타내며,
    // 반환값이 없는 함수나 세미콜론으로 끝나는 블록이 내는 값입니다(08_expressions 참고).
    let unit = ();
    println!("unit = {unit:?}"); // 출력: unit = ()

    // ── 2. 배열: 같은 타입의 값 여러 개를 고정된 길이로 묶습니다 ────────────
    // 타입은 `[원소 타입; 길이]`로 씁니다. 길이도 타입의 일부여서 `[i32; 5]`와 `[i32; 3]`은 다른 타입입니다.
    let a: [i32; 5] = [1, 2, 3, 4, 5];
    println!("a = {a:?}, 길이 = {}", a.len()); // 출력: a = [1, 2, 3, 4, 5], 길이 = 5

    // `[값; 개수]`는 같은 값을 개수만큼 채운 배열을 만듭니다.
    let zeros = [0; 4];
    println!("zeros = {zeros:?}"); // 출력: zeros = [0, 0, 0, 0]

    // 대괄호 인덱스로 원소에 접근합니다. 인덱스는 0부터 시작하고 타입은 `usize`입니다.
    let first = a[0];
    let last = a[a.len() - 1];
    println!("첫 원소 = {first}, 마지막 원소 = {last}"); // 출력: 첫 원소 = 1, 마지막 원소 = 5

    // 개수가 바뀌지 않는 데이터에 배열이 잘 맞습니다. 개수가 변해야 한다면 ch8의 `Vec`를 씁니다.
    let weekdays = ["월", "화", "수", "목", "금", "토", "일"];
    println!("셋째 요일 = {}", weekdays[2]); // 출력: 셋째 요일 = 수

    // `mut` 배열은 원소를 바꿀 수 있습니다.
    let mut scores = [70, 80, 90];
    scores[1] = 85;
    println!("scores = {scores:?}"); // 출력: scores = [70, 85, 90]

    // ── 3. 범위 밖 접근을 패닉 없이 확인하기 ─────────────────────────────────
    // `a[10]`처럼 범위 밖을 인덱싱하면 Rust는 잘못된 메모리를 읽는 대신 프로그램을 멈춥니다(패닉).
    // 실제로 패닉하는 모습은 06_array_index 예제에서 확인합니다.
    // `get`은 같은 상황에서 패닉하지 않고 `Some(값)` 또는 `None`(범위 밖)을 돌려줍니다.
    // (`Option` 타입은 ch6에서 다룹니다.)
    println!("a.get(1)  = {:?}", a.get(1)); // 출력: a.get(1)  = Some(2)
    println!("a.get(10) = {:?}", a.get(10)); // 출력: a.get(10) = None
}
