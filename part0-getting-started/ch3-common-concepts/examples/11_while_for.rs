// 이 예제가 보여 주는 것: 조건 반복 `while`과 컬렉션·범위 반복 `for`, 그리고 `for`가 더 안전한 이유
// 실행: cargo run -p p0-ch3-common-concepts --example 11_while_for

fn main() {
    // ── 1. `while`: 조건이 참인 동안 반복합니다 ──────────────────────────────
    // `loop` + `if` + `break`로도 만들 수 있지만, "조건이 참인 동안"이라는 의도가 더 잘 드러납니다.
    let mut number = 3;
    while number != 0 {
        println!("{number}!");
        number -= 1;
    }
    println!("발사!");
    // 출력:
    // 3!
    // 2!
    // 1!
    // 발사!

    // ── 2. 배열을 인덱스로 순회하는 `while` ─────────────────────────────────
    // 동작은 하지만, 조건 `index < 5`를 배열 길이와 직접 맞춰야 합니다.
    // 배열 길이를 바꾸고 조건을 고치지 않으면 범위 밖 접근으로 패닉하거나 원소를 빠뜨립니다.
    let a = [10, 20, 30, 40, 50];
    let mut index = 0;
    while index < 5 {
        print!("[{}]", a[index]); // `print!`은 줄바꿈 없이 출력합니다.
        index += 1;
    }
    println!(); // 줄바꿈만 출력합니다.
    // 출력: [10][20][30][40][50]

    // ── 3. `for`: 배열의 원소를 하나씩 꺼냅니다 ─────────────────────────────
    // 인덱스를 직접 다루지 않으므로 길이가 바뀌어도 코드를 고칠 필요가 없고,
    // 범위 밖 접근이 일어날 수 없습니다. Rust에서 가장 많이 쓰는 반복문입니다.
    for element in a {
        print!("[{element}]");
    }
    println!();
    // 출력: [10][20][30][40][50]

    // ── 4. 범위(range)와 `for` ─────────────────────────────────────────────
    // `1..4`는 1 이상 4 미만(1, 2, 3), `1..=4`는 1 이상 4 이하(1, 2, 3, 4)입니다.
    for i in 1..4 {
        print!("[{i}]");
    }
    println!();
    // 출력: [1][2][3]

    let mut sum = 0;
    for i in 1..=100 {
        sum += i;
    }
    println!("1부터 100까지의 합 = {sum}"); // 출력: 1부터 100까지의 합 = 5050

    // `.rev()`를 붙이면 범위를 거꾸로 순회합니다. 1번의 카운트다운을 `for`로 다시 쓴 것입니다.
    for number in (1..4).rev() {
        println!("{number}!");
    }
    println!("발사!");
    // 출력:
    // 3!
    // 2!
    // 1!
    // 발사!

    // 원소와 함께 인덱스도 필요하면 `.iter().enumerate()`를 붙입니다.
    // 반복할 때마다 (인덱스, 원소) 튜플을 내주므로, 튜플 구조 분해 패턴으로 받습니다.
    // 인덱스로 다시 배열을 인덱싱하지 않으므로 범위 밖 접근이 일어날 여지가 없습니다.
    // (`iter`, `enumerate` 같은 반복자(iterator) 메서드는 ch13에서 자세히 다룹니다.)
    let weekdays = ["월", "화", "수"];
    for (i, day) in weekdays.iter().enumerate() {
        println!("{i}번째 요일: {day}");
    }
    // 출력:
    // 0번째 요일: 월
    // 1번째 요일: 화
    // 2번째 요일: 수
}
