// 배열 슬라이스(`&[T]`)는 배열의 연속된 일부를 가리키는 참조입니다.
// 길이가 타입에 들어가지 않으므로, 길이가 다른 배열을 함수 하나로 다룰 수 있습니다.
//
// 실행: cargo run -p p0-ch4-ownership --example 07_array_slices

// `&[i32]`는 "i32가 몇 개인지 모르는 연속된 구간"을 빌려 옵니다.
// `[i32; 5]`처럼 길이가 정해진 배열 타입으로 받으면 길이가 5인 배열만 넘길 수 있습니다.
fn sum(numbers: &[i32]) -> i32 {
    let mut total = 0;
    for n in numbers {
        // 슬라이스를 for로 돌면 각 원소의 참조(&i32)를 받으므로 `*`로 값을 꺼냅니다.
        total += *n;
    }
    total
}

// `&mut [i32]`는 빌려 온 구간의 원소를 바꿀 수 있는 가변 슬라이스입니다.
fn fill_zero(part: &mut [i32]) {
    for n in part {
        // 가변 슬라이스를 for로 돌면 각 원소의 가변 참조(&mut i32)를 받습니다.
        *n = 0;
    }
}

fn main() {
    println!("1. 범위 문법으로 배열의 일부를 빌립니다");
    let a = [1, 2, 3, 4, 5];
    let middle = &a[1..3]; // 1번, 2번 원소. 타입은 &[i32]입니다.
    // `{:?}`는 배열·슬라이스를 디버그 형식으로 출력합니다(ch5에서 자세히 다룹니다).
    println!("    middle = {middle:?}, 길이 = {}", middle.len());
    // 출력:
    //     middle = [2, 3], 길이 = 2

    println!("2. &[i32] 매개변수는 배열 전체, 배열의 일부, 길이가 다른 배열을 모두 받습니다");
    let b = [10, 20, 30];
    println!("    sum(&a)      = {}", sum(&a)); // &[i32; 5]가 &[i32]로 자동 변환됩니다.
    println!("    sum(&a[..2]) = {}", sum(&a[..2]));
    println!("    sum(&a[3..]) = {}", sum(&a[3..]));
    println!("    sum(&b)      = {}", sum(&b)); // 길이가 3인 배열도 같은 함수로 받습니다.
    // 출력:
    //     sum(&a)      = 15
    //     sum(&a[..2]) = 3
    //     sum(&a[3..]) = 9
    //     sum(&b)      = 60

    println!("3. 가변 슬라이스로 배열의 일부만 바꿉니다");
    let mut c = [1, 2, 3, 4, 5];
    fill_zero(&mut c[2..]); // 2번 원소부터 끝까지만 빌려줍니다.
    println!("    c = {c:?}");
    // 출력:
    //     c = [1, 2, 0, 0, 0]
    // 빌려주지 않은 앞부분 [1, 2]는 함수가 건드릴 수 없습니다.

    println!("4. 슬라이스도 참조이므로 대여 규칙을 따릅니다");
    let mut d = [7, 8, 9];
    let view = &d[..]; // d를 불변으로 빌리는 중
    println!("    view = {view:?}"); // ← view의 마지막 사용
    d[0] = 70; // 불변 대여가 끝났으므로 수정할 수 있습니다.
    println!("    d = {d:?}");
    // 출력:
    //     view = [7, 8, 9]
    //     d = [70, 8, 9]
    // view를 d[0] = 70 아래에서 다시 쓰면 E0506(빌려준 동안 대입할 수 없음)이 납니다.
}
